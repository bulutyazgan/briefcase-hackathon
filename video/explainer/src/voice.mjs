// One spoken line per caption (gpt-4o-mini-tts, voice onyx, calm). Measures each line and writes
// captions-timing.js / captions-timing.json so the burned-in captions, captions.srt and the audio
// mix all share one set of times. Needs OPENAI_API_KEY in the environment; the key is never printed.
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const TIMELINE = createRequire(import.meta.url)('./timeline.js')
import { readFileSync } from 'node:fs'
function keyFromEnvFile() {
  const envFile = process.env.TALLY_ENV_FILE || '/home/user/briefcase-hackathon/server/.env'
  if (!existsSync(envFile)) return ''
  const line = readFileSync(envFile, 'utf8').split('\n').find(l => l.startsWith('OPENAI_API_KEY='))
  return line ? line.slice('OPENAI_API_KEY='.length).trim().replace(/^["']|["']$/g, '') : ''
}
const key = process.env.OPENAI_API_KEY || keyFromEnvFile()
if (!key) { console.error('OPENAI_API_KEY missing'); process.exit(1) }
const dir = resolve(here, 'voice')
mkdirSync(dir, { recursive: true })

const timing = []
let prevEnd = 0
const caps = TIMELINE.captions
for (let i = 0; i < caps.length; i++) {
  const c = caps[i]
  const file = resolve(dir, `${c.id}.mp3`)
  if (!existsSync(file)) {
    const res = await fetch('https://api.openai.com/v1/audio/speech', {
      method: 'POST',
      headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ model: 'gpt-4o-mini-tts', voice: 'onyx', input: c.text, response_format: 'mp3', speed: 1.0, instructions: 'Calm, warm, unhurried British narrator for a product explainer. Plain delivery, no sales energy. Pause briefly at full stops.' }),
    })
    if (!res.ok) { console.error(`${c.id}: ${res.status} ${(await res.text()).slice(0, 200)}`); process.exit(1) }
    writeFileSync(file, Buffer.from(await res.arrayBuffer()))
  }
  // Trim silence at both ends, then fit the line to its planned slot (tempo change capped at 1.2).
  const trimmed = resolve(dir, `${c.id}.trim.wav`)
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', file, '-af', 'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.15,areverse', '-ar', '48000', trimmed])
  const probe = f => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim())
  const rawDur = probe(trimmed)
  const slotEnd = (caps[i + 1] ? caps[i + 1].t0 : TIMELINE.duration - 0.4) - 0.25
  const slot = slotEnd - c.t0
  const tempo = Math.min(1.2, Math.max(1, rawDur / slot))
  const fit = resolve(dir, `${c.id}.fit.wav`)
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', trimmed, '-af', `atempo=${tempo.toFixed(4)}`, fit])
  const dur = probe(fit)
  const t0 = Math.max(c.t0, prevEnd + 0.25)
  const t1 = Math.round((t0 + dur) * 100) / 100
  timing.push({ id: c.id, t0: Math.round(t0 * 100) / 100, t1, planned: c.t0, dur: Math.round(dur * 100) / 100, tempo: Number(tempo.toFixed(3)), text: c.text, file: `voice/${c.id}.fit.wav` })
  prevEnd = t1
  console.log(`${c.id} planned ${c.t0.toFixed(2)} -> ${t0.toFixed(2)}..${t1.toFixed(2)} raw ${rawDur.toFixed(2)}s tempo ${tempo.toFixed(2)}${t0 - c.t0 > 0.05 ? '  SHIFTED' : ''}`)
}
writeFileSync(resolve(here, 'captions-timing.json'), JSON.stringify(timing, null, 2))
writeFileSync(resolve(here, 'captions-timing.js'), `// Generated by voice.mjs from measured voice lines. Do not edit by hand.\nwindow.CAPTIONS_TIMING = ${JSON.stringify(timing.map(({ id, t0, t1, text }) => ({ id, t0, t1, text })))}\n`)
console.log(`voice ends at ${prevEnd.toFixed(2)}s of ${TIMELINE.duration}s`)
