import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { Document, Page, StyleSheet, Text, View } from '@formepdf/react'
import { renderDocument } from '@formepdf/core'
import { RATE_PENCE, type PricedLine } from '../policy/decide'

const styles = StyleSheet.create({
  title: { fontSize: 24, fontWeight: 700, marginBottom: 20 },
  heading: { fontSize: 16, fontWeight: 700, marginBottom: 12 },
  text: { fontSize: 11, lineHeight: 1.5, marginBottom: 8 },
  muted: { fontSize: 9, color: '#626b75', marginBottom: 5 },
  rule: { borderBottomWidth: 1, borderBottomColor: '#d7dce1', marginBottom: 14, paddingBottom: 12 },
  row: { flexDirection: 'row', justifyContent: 'space-between', marginBottom: 10 },
})

interface PdfInvoice {
  invoiceId: string
  clientName: string
  totalPence: number
  lines: PricedLine[]
}

function pounds(amountPence: number): string {
  return `£${(amountPence / 100).toFixed(2)}`
}

export async function renderInvoicePdf(invoice: PdfInvoice): Promise<string> {
  const document = (
    <Document title={`Tally invoice ${invoice.invoiceId}`}>
      <Page size="A4" margin={48}>
        <Text style={styles.title}>Tally invoice</Text>
        <Text style={styles.text}>Invoice reference: {invoice.invoiceId}</Text>
        <Text style={styles.text}>Bill to: {invoice.clientName}</Text>
        <Text style={styles.text}>Payment terms: 7 days</Text>
        <View style={styles.rule} />
        {invoice.lines.map((line, index) => (
          <View key={`${line.description}-${index}`} style={styles.row}>
            <View>
              <Text style={styles.text}>{line.description} · {line.quantity} × {pounds(RATE_PENCE)}</Text>
              {line.quantity * line.unitPricePence > line.totalPence && (
                <Text style={styles.muted}>
                  Agreed discount: {pounds(line.quantity * line.unitPricePence - line.totalPence)}
                </Text>
              )}
            </View>
            <Text style={styles.text}>{pounds(line.totalPence)}</Text>
          </View>
        ))}
        <View style={styles.rule} />
        <Text style={styles.heading}>Total due {pounds(invoice.totalPence)}</Text>
        <Text style={styles.muted}>Generated by Tally</Text>
      </Page>
      <Page size="A4" margin={48}>
        <Text style={styles.title}>Why this invoice</Text>
        <Text style={styles.muted}>Evidence appendix · {invoice.invoiceId}</Text>
        {invoice.lines.map((line, index) => (
          <View key={`${line.description}-${index}`} style={styles.rule}>
            <Text style={styles.heading}>{line.description}</Text>
            <Text style={styles.muted}>Client quote</Text>
            <Text style={styles.text}>“{line.quote}”</Text>
            <Text style={styles.muted}>Memory fact</Text>
            <Text style={styles.text}>{line.memoryFact}</Text>
            <Text style={styles.muted}>Policy clauses</Text>
            <Text style={styles.text}>{line.clauses.join(', ')}</Text>
          </View>
        ))}
      </Page>
    </Document>
  )
  const bytes = await renderDocument(document)
  const outputDirectory = join(process.cwd(), 'out')
  await mkdir(outputDirectory, { recursive: true })
  const outputPath = join(outputDirectory, `${invoice.invoiceId}.pdf`)
  await writeFile(outputPath, bytes)
  return outputPath
}
